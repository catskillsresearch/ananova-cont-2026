"""Generate WeakPathwiseItoComparator/Challenge.lean (statement of record: Mathlib plus vendored libraries).

Flattens, in import order, the WeakPathwiseIto modules in the import closure of the compared
theorems' modules (COMPARED_MODULES). Each module body is copied verbatim inside its own
`section … end`, so `variable`s stay local. Proof bodies are kept as written (never replaced
by `sorry`).

Theorems/lemmas (and `**Subgoal**`-labelled helper defs) that neither are compared nor are
referenced by anything kept are omitted: their text is commented out completely in the copied
body, so they add no declarations to the Challenge.

Imports. Besides Mathlib, the Challenge imports the vendored libraries (`vendor/`, part of the
submission) that the copied modules import, e.g. `BrownianMotion.*`; see VENDOR_PREFIXES.

    python3 scripts/gen_challenge.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIB = "WeakPathwiseIto"
OUT = ROOT / "WeakPathwiseItoComparator" / "Challenge.lean"
COMPARED_MODULES = ["Main.Theorem51", "Main.Theorem52", "Main.Proposition53"]
IMPORT_RE = re.compile(r"^\s*public import " + LIB + r"\.([A-Za-z0-9_.]+)\s*$", re.M)
EXT_IMPORT_RE = re.compile(r"^\s*public import ([A-Za-z0-9_.]+)\s*$", re.M)
# Top-level module prefixes of vendored libraries (vendor/, part of the submission) that the
# Challenge may import when a copied module imports them.
VENDOR_PREFIXES = ("BrownianMotion",)
OMIT_NOTE = "/- [omitted from the Challenge: not used by the compared statements]\n"

RESET = "run_cmd Lean.modifyEnv fun env => Lean.Meta.auxLemmasExt.setState env {}"

HEADER = f"""/-
Copyright (c) 2026 Lars Warren Ericson
Released under Apache-2.0 license as described in file LICENSE.
-/
module

public import Mathlib
@@VENDOR_IMPORTS@@meta import Lean.Meta.Tactic.AuxLemma

/-!
# Palomar Challenge (generated by `scripts/gen_challenge.py`; do not edit)

Statement of record (Mathlib plus the vendored `vendor/` libraries) for A. Ananova and R. Cont, *A pathwise Ito formula for
weakly differentiable functions*, arXiv:2608.07365v2. The definitions below are copied
verbatim, in import order, from the `{LIB}/` library; supporting lemmas that the compared
statements do not use are omitted. The compared theorems are listed in `comparator.json`.

Lean caches auxiliary `_proof_N` lemmas per file (`Lean.Meta.mkAuxLemma`), so each source
module's block starts by clearing that cache: the Challenge then regenerates exactly the
auxiliary lemmas of the per-module library build (technique from xodarev2026's
`scripts/gen_challenge.py`).
-/

@[expose] public section

set_option warn.sorry false

noncomputable section

open MeasureTheory Filter Topology Set
open scoped ENNReal NNReal RealInnerProductSpace

"""


def path_of(mod: str) -> Path:
    return ROOT / LIB / (mod.replace(".", "/") + ".lean")


def body_of(mod: str) -> str:
    text = path_of(mod).read_text(encoding="utf-8")
    start = text.index(f"namespace {LIB}\n")
    end = text.rindex(f"end {LIB}")
    # Keep the module's own top-level `open` commands (e.g. `open scoped Pointwise`): they sit
    # before `namespace WeakPathwiseIto` and affect elaboration of the copied body. They are
    # emitted inside the module's `section … end`, so they stay local to that module.
    opens = [ln for ln in text[:start].splitlines() if re.match(r"^open\b", ln)]
    body = text[start + len(f"namespace {LIB}\n"):end].strip("\n")
    return ("\n".join(opens) + "\n\n" + body) if opens else body


THM_RE = re.compile(r"^(?:theorem|lemma)\s+([^\s:({\[]+)", re.M)
SUBGOAL_DEF_RE = re.compile(r"^(?:noncomputable\s+)?def\s+([^\s:({\[]+)", re.M)


def prune(body: str, compared: set[str], keep_text: str) -> str:
    """Drop theorem/lemma chunks that are neither compared nor referenced elsewhere."""
    chunks = re.split(r"\n\s*\n", body)
    out = []
    for ch in chunks:
        m = THM_RE.search(ch)
        if not m and "**Subgoal**" in ch:
            # helper defs labelled as subgoals are pruned like helper lemmas
            m = SUBGOAL_DEF_RE.search(ch)
        if m:
            name = m.group(1)
            short = name.split(".")[-1]
            others = re.sub(r"/-.*?-/|--[^\n]*", "", keep_text.replace(ch, ""), flags=re.S)
            others = THM_RE.sub("theorem", others)
            if not any(c.endswith("." + short) or c == short for c in compared) and \
                    not re.search(r"(?<![A-Za-z0-9_])" + re.escape(short) + r"(?![A-Za-z0-9_'])", others):
                continue
        out.append(ch)
    return "\n\n".join(out)


def closure() -> list[str]:
    order, seen = [], set()

    def visit(m: str) -> None:
        if m in seen:
            return
        seen.add(m)
        for d in IMPORT_RE.findall(path_of(m).read_text(encoding="utf-8")):
            visit(d)
        order.append(m)

    for m in COMPARED_MODULES:
        visit(m)
    return order


def prune_all(bodies: list[str], compared: set[str]) -> list[str]:
    """Iterate `prune` to a fixed point, so lemmas only used by pruned lemmas also go."""
    while True:
        alltext = "\n".join(bodies)
        new = [prune(b, compared, alltext) for b in bodies]
        new = [re.sub(r"\n{3,}", "\n\n", re.sub(r"(?m)^namespace (\S+)\n\s*\nend \1$", "", b))
               for b in new]
        if new == bodies:
            return bodies
        bodies = new


def vendor_imports(mods: list[str]) -> list[str]:
    """Vendored-library imports of the copied modules, in first-seen order."""
    out: list[str] = []
    for m in mods:
        for imp in EXT_IMPORT_RE.findall(path_of(m).read_text(encoding="utf-8")):
            if imp.split(".")[0] in VENDOR_PREFIXES and imp not in out:
                out.append(imp)
    return out


def nests_safely(chunk: str) -> bool:
    """True if wrapping `chunk` in `/- … -/` comments it out exactly (Lean block comments nest):
    every `/-`/`-/` outside block comments is balanced, and no line comment or string literal
    contains a comment delimiter."""
    t = chunk
    while True:
        u = re.sub(r"/-(?:(?!/-|-/).)*-/", "", t, flags=re.S)
        if u == t:
            break
        t = u
    if "/-" in t or "-/" in t:
        return False
    return not re.search(r'"[^"\n]*(?:/-|-/)[^"\n]*"', t)


def comment_out_pruned(original: str, kept: str) -> str:
    """Re-insert the theorem/lemma (and subgoal-def) chunks `prune_all` dropped, each commented
    out completely; other chunks (namespace/section lines, defs) are kept as written."""
    kept_chunks = set(re.split(r"\n\s*\n", kept))
    out = []
    for ch in re.split(r"\n\s*\n", original):
        dropped = ch not in kept_chunks and (
            THM_RE.search(ch) or ("**Subgoal**" in ch and SUBGOAL_DEF_RE.search(ch)))
        if not dropped:
            out.append(ch)
            continue
        if not nests_safely(ch):
            raise SystemExit("cannot comment out chunk safely:\n" + ch[:200])
        out.append(OMIT_NOTE + ch + "\n-/")
    return "\n\n".join(out)


def tidy(body: str) -> str:
    """Collapse runs of blank lines left by pruned chunks."""
    return re.sub(r"\n[ \t]*\n(?:[ \t]*\n)+", "\n\n", body).strip("\n")


def main() -> None:
    cfg = json.loads((ROOT / "comparator.json").read_text(encoding="utf-8"))
    mods = closure()
    vimps = "".join(f"public import {i}\n" for i in vendor_imports(mods))
    parts = [HEADER.replace("@@VENDOR_IMPORTS@@", vimps), f"namespace {LIB}\n"]
    compared = set(cfg["theorem_names"])
    originals = [body_of(m) for m in mods]
    bodies = [comment_out_pruned(o, k) for o, k in zip(originals, prune_all(originals, compared))]
    for m, body in zip(mods, bodies):
        parts.append(f"\n/-! ## `{LIB}.{m}` -/\n\n{RESET}\n\nsection\n\n{tidy(body)}\n\nend\n")
    parts.append(f"\nend {LIB}\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(closure())} modules, "
          f"{len(cfg['theorem_names'])} compared theorems)")


if __name__ == "__main__":
    main()
